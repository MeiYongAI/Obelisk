private val artByName = BattleMark.entries.filter { it.actionName.isNotEmpty() }
    .associateBy({ it.actionName }, { it.art })
private val artByKey = BattleMark.entries.filter { it.key != null }.associateBy({ it.key }, { it.art })

internal fun battleGlyphFor(iconKey: String?, name: String): Pair<GameGlyph, ArtPalette>? =
    if (name == "Defend") BattleMark.Protection.art else artByName[name] ?: artByKey[iconKey]

internal fun stanceGlyph(mode: String): Pair<GameGlyph, ArtPalette> = when (mode) {
    "spirit" -> BattleMark.SpiritStance.art
    "defend" -> BattleMark.Protection.art
    else -> BattleMark.Focus.art
}

internal fun defaultBattleGlyph(group: String): Pair<GameGlyph, ArtPalette> = when (group) {
    "Weapon" -> BattleMark.GreatCleave.art
    "Innate" -> BattleMark.SpiritStance.art
    "Curative" -> BattleMark.Cure.art
    "Supportive" -> BattleMark.Protection.art
    "Deprecating" -> BattleMark.Imperil.art
    else -> BattleMark.GenericMagic.art
}
